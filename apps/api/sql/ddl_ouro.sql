-- DDL da camada ouro, equivalente ao metadata de schema.py depois da FK de cod.
-- O runtime continua no Alembic (001_initial e 002_fk_cod).

CREATE TABLE dim_territorio (
	cod INTEGER NOT NULL, 
	sigla VARCHAR(8) NOT NULL, 
	local VARCHAR(80) NOT NULL, 
	nivel VARCHAR(16) NOT NULL, 
	regiao_cod INTEGER, 
	PRIMARY KEY (cod)
);

CREATE TABLE dim_metrica (
	dataset_id VARCHAR(8) NOT NULL, 
	coluna VARCHAR(64) NOT NULL, 
	rotulo VARCHAR(120) NOT NULL, 
	descricao VARCHAR(255) NOT NULL, 
	unidade VARCHAR(40) NOT NULL, 
	PRIMARY KEY (dataset_id, coluna)
);

CREATE TABLE etl_runs (
	id INTEGER NOT NULL AUTO_INCREMENT, 
	dataset_id VARCHAR(8) NOT NULL, 
	source VARCHAR(16) NOT NULL, 
	status VARCHAR(16) NOT NULL, 
	started_at DATETIME NOT NULL DEFAULT now(), 
	finished_at DATETIME, 
	rows_in INTEGER, 
	rows_out INTEGER, 
	report_json JSON, 
	error TEXT, 
	PRIMARY KEY (id)
);

CREATE TABLE ds1_populacao_idade (
	idade INTEGER, 
	sexo VARCHAR(24), 
	cod INTEGER, 
	sigla VARCHAR(8), 
	local VARCHAR(80), 
	nivel VARCHAR(16), 
	ano INTEGER, 
	populacao FLOAT, 
	is_outlier BOOL, 
	outlier_motivo TEXT, 
	CONSTRAINT fk_ds1_populacao_idade_cod FOREIGN KEY(cod) REFERENCES dim_territorio (cod), 
	CONSTRAINT uq_ds1_populacao_idade UNIQUE (idade, sexo, cod, ano)
);

CREATE INDEX ix_ds1_populacao_idade_cod_ano ON ds1_populacao_idade (cod, ano);

